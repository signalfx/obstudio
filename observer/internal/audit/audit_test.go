func TestParseUninstrumentedReport(t *testing.T) {
	got := Parse(uninstrumentedReport)

	if got.ServiceName != "checkout" {
		t.Errorf("ServiceName = %q, want %q", got.ServiceName, "checkout")
	}
	if got.Language != "Python (>=3.11)" {
		t.Errorf("Language = %q", got.Language)
	}
	if got.Rate != REDMissing || got.Errors != REDMissing || got.Duration != REDMissing {
		t.Errorf("RED = %s/%s/%s, want all missing", got.Rate, got.Errors, got.Duration)
	}
	if got.HasSpans || got.HasMetrics || got.HasLogs {
		t.Errorf("signals = spans:%v metrics:%v logs:%v, want all false", got.HasSpans, got.HasMetrics, got.HasLogs)
	}
	if got.GapCount != 6 {
		t.Errorf("GapCount = %d, want 6", got.GapCount)
	}
	if got.AntiPatternCount != 2 {
		t.Errorf("AntiPatternCount = %d, want 2", got.AntiPatternCount)
	}

	// Coverage 0; quality = anti-patterns max(0, 15-10)=5, gaps max(0, 15-18)=0.
	if got.Score != 5 {
		t.Errorf("Score = %d, want 5", got.Score)
	}
}

func TestParseInstrumentedReport(t *testing.T) {
	got := Parse(instrumentedReport)

	if got.Rate != REDCovered || got.Errors != REDCovered || got.Duration != REDCovered {
		t.Errorf("RED = %s/%s/%s, want all covered", got.Rate, got.Errors, got.Duration)
	}
	if !got.HasSpans || !got.HasMetrics || !got.HasLogs {
		t.Errorf("signals = spans:%v metrics:%v logs:%v, want all true", got.HasSpans, got.HasMetrics, got.HasLogs)
	}
	if got.GapCount != 3 {
		t.Errorf("GapCount = %d, want 3", got.GapCount)
	}
	if got.RecommendationCount != 2 {
		t.Errorf("RecommendationCount = %d, want 2", got.RecommendationCount)
	}
	if len(got.Gaps) != 3 || got.Gaps[0] != "No OTLP log pipeline." {
		t.Errorf("Gaps = %q, want the three gap sentences", got.Gaps)
	}
	if len(got.Recommendations) != 2 || got.Recommendations[0] != "Instrumentation is complete for RED." {
		t.Errorf("Recommendations = %q", got.Recommendations)
	}
	// "None detected." suppresses the section, so no bullet text leaks through.
	if len(got.AntiPatterns) != 0 {
		t.Errorf("AntiPatterns = %q, want none", got.AntiPatterns)
	}

	// Coverage 45+10+10+5=70; quality = 15 (no anti-patterns) + max(0,15-9)=6.
	if got.Score != 91 {
		t.Errorf("Score = %d, want 91", got.Score)
	}
	if got.Breakdown.Coverage != 70 {
		t.Errorf("Coverage = %v, want 70", got.Breakdown.Coverage)
	}
	if got.Breakdown.Quality != 21 {
		t.Errorf("Quality = %v, want 21", got.Breakdown.Quality)
	}
}


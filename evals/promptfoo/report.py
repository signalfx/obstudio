"""Publish/verify the pilot's compact latest local attestation; never edit raw runs."""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

from adapter import JUDGE_SCHEMA, ROOT, digest, gate, source_manifest, tree
from jsonschema import validate
from routing import select

DESTINATION = ROOT / "eval-reports/promptfoo-pilot"


def verify(result: dict) -> None:
    if result.get("schema_version") != 1:
        raise ValueError("unknown or missing pilot schema")
    if result.get("isolation") != {"active": True, "config_sha256": digest(ROOT / "evals/codex-eval-home.config.toml"), "home_mode": "fresh-per-actor"}:
        raise ValueError("isolated evaluator configuration was not proven")
    validate(result["raw_grade"], JUDGE_SCHEMA)
    if result["raw_grade"]["checks"] != result["checks"]:
        raise ValueError("raw automated grade was altered")
    expected = [f"rubric-{i}" for i in range(1, 1 + len(json.loads(
        (ROOT / "evals/python/flask-basic/eval/qual/audit.json").read_text())["rubric"]))]
    reasons = gate(result["checks"], expected, result["guards"], result["errors"])
    if result.get("gate") is not True or reasons:
        raise ValueError(f"eval did not pass required criteria: {reasons}")
    if result["source_files"] != source_manifest():
        raise ValueError("pilot evidence is stale; rerun npm run eval and npm run report")


def load_run(directory: Path) -> tuple[dict, dict]:
    result = json.loads((directory / "evidence/result.json").read_text())
    verify(result)
    exported = json.loads((directory / "promptfoo.json").read_text())
    stats = exported["results"]["stats"]
    if stats["successes"] != 1 or stats["failures"] != 0 or stats["errors"] != 0:
        raise ValueError(f"Promptfoo did not grade exactly one successful case: {stats}")
    if tree(directory / "evidence/agent") != result["agent_artifacts"]:
        raise ValueError("raw agent artifacts changed after evaluation")
    if json.loads((directory / "evidence/judge/rubric_grade.json").read_text()) != result["raw_grade"]:
        raise ValueError("raw judge grade changed after evaluation")
    return result, stats


def block(text: str, language: str = "text") -> str:
    # Untrusted evidence cannot close its fence or introduce rendered HTML/links.
    fence = "`" * max(3, max((len(run) for run in re.findall(r"`+", text)), default=0) + 1)
    return f"{fence}{language}\n{text}\n{fence}"


def publish(directory: Path) -> None:
    result, stats = load_run(directory)
    # Keep the automated statuses, reasons and evidence verbatim. Human notes belong elsewhere.
    proof = {**result, "promptfoo_stats": stats, "promptfoo_version": "0.126.0"}
    DESTINATION.mkdir(parents=True, exist_ok=True)
    (DESTINATION / "benchmark.json").write_text(json.dumps(proof, indent=2) + "\n")
    lines = ["# Promptfoo audit pilot — latest local proof", "",
             "Generated by `npm run report -- <run-directory>`. This is a local attestation, not a CI model run.", "",
             f"Gate: **PASS**. Promptfoo 0.126.0; {result['codex_version']}; {result['duration_seconds']} seconds.",
             f"Requested models: `{result['requested_models']}`. Cost unavailable (CLI login).",
             f"Evaluated commit: `{result['evaluated_commit']}`; exact input SHA-256 values are in benchmark.json.",
             "Model names are requested identities; the CLI trace may not report the resolved server model.", "",
             "Original task:", "", "```text", result["original_prompt"], "```", "",
             "Exact harness prompt:", "", "```text", result["effective_prompt"], "```", "",
             "Source rubric: `evals/python/flask-basic/eval/qual/audit.json`.",
             "Pilot-added Example/Evidence/Insufficient evidence guidance is preserved in the raw judge-prompt.txt.",
             "Rule 6 is graded as one compound rule, requiring evidence for all its clauses.", ""]
    by_id = {check["id"]: check for check in result["checks"]}
    for rule in result["rules"]:
        check = by_id[rule["id"]]
        lines += [f"## {rule['id']}: {check['status']}", "", f"Rule: {rule['rule']}", "",
                  block(f"Judge reason: {check['reason']}\nEvidence: {check['evidence']}"), ""]
    lines += ["## Actual canonical audit excerpt", "", result["audit_excerpt_note"], "",
              block(result["audit_excerpt"] or "No audit artifact", "json"), ""]
    lines += ["## Deterministic evidence", "", "```json", json.dumps(result["guards"], indent=2), "```", "",
              "Full raw agent/judge traces, final response, canonical JSON/HTML, exact judge prompt and schema,",
              "artifact hashes, and the native Promptfoo export/viewer database remain in the local run directory:",
              "", f"`{directory}`", "",
              "benchmark.json preserves the unedited judge JSON, status checks, source and artifact hashes.",
              "No raw traces or reports were shared with a hosted service. Local viewer ratings do not update this proof.", ""]
    (DESTINATION / "report.md").write_text("\n".join(lines))
    print(f"Published {DESTINATION}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--check-run", type=Path)
    group.add_argument("--publish", type=Path)
    group.add_argument("--base")
    args = parser.parse_args()
    if args.check_run:
        load_run(args.check_run)
        print("Promptfoo export and required evidence passed")
    elif args.publish:
        publish(args.publish)
    else:
        selection = select(ROOT, args.base, "HEAD")
        print(json.dumps(selection, indent=2))
        if selection["selected"]:
            verify(json.loads((DESTINATION / "benchmark.json").read_text()))
            print("Selected audit: fresh passing local model attestation (not a CI model run)")

// A nil slice would marshal to null and break clients that iterate the field.
func TestFindingSlicesMarshalAsArrays(t *testing.T) {
	got := Parse(instrumentedReport)

	raw, err := json.Marshal(got)
	if err != nil {
		t.Fatal(err)
	}
	body := string(raw)

	for _, field := range []string{`"gaps":null`, `"antiPatterns":null`, `"recommendations":null`} {
		if strings.Contains(body, field) {
			t.Errorf("JSON contains %s; want an empty array instead", field)
		}
	}
	if !strings.Contains(body, `"antiPatterns":[]`) {
		t.Errorf("antiPatterns should marshal as [], got: %s", body)
	}
}

func TestReadRawReturnsSource(t *testing.T) {
	root := t.TempDir()
	if err := os.MkdirAll(filepath.Join(root, ".observe"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, ".observe", "otel.md"), []byte(instrumentedReport), 0o600); err != nil {
		t.Fatal(err)
	}

	r := NewResolver(Config{WorkspaceRoot: root})
	raw, err := r.ReadRaw()
	if err != nil {
		t.Fatalf("ReadRaw: %v", err)
	}
	if string(raw) != instrumentedReport {
		t.Error("ReadRaw returned different content than the file holds")
	}
	if r.Source() != "otel.md" {
		t.Errorf("Source() = %q, want basename only", r.Source())
	}
}


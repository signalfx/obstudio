// ReadRaw must obey the same traversal guard as Build.
func TestReadRawHonorsPathGuard(t *testing.T) {
	root := t.TempDir()
	outside := filepath.Join(t.TempDir(), "secret.md")
	if err := os.WriteFile(outside, []byte("# secret\n"), 0o600); err != nil {
		t.Fatal(err)
	}

	r := NewResolver(Config{WorkspaceRoot: root, ReportPath: outside})

	_, err := r.ReadRaw()
	if !errors.Is(err, ErrNoReport) {
		t.Errorf("err = %v, want ErrNoReport (path outside workspace must not be read)", err)
	}
}

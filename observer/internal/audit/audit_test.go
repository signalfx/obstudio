func TestPartialSignalsScoreHalf(t *testing.T) {
	report := strings.Replace(instrumentedReport, "| Rate | covered |", "| Rate | partial |", 1)
	got := Parse(report)

	if got.Rate != REDPartial {
		t.Fatalf("Rate = %s, want partial", got.Rate)
	}
	// 91 - 7.5 = 83.5, rounds to 84.
	if got.Score != 84 {
		t.Errorf("Score = %d, want 84", got.Score)
	}
}

func TestScoreIsBounded(t *testing.T) {
	manyGaps := strings.Replace(uninstrumentedReport, "## Gaps\n", "## Gaps\n"+strings.Repeat("- another gap\n", 50), 1)
	got := Parse(manyGaps)

	if got.Score < 0 || got.Score > 100 {
		t.Errorf("Score = %d, want within [0,100]", got.Score)
	}
}

func TestBuildMissingReport(t *testing.T) {
	r := NewResolver(Config{WorkspaceRoot: t.TempDir()})
	got := r.Build()

	if got.Available {
		t.Error("Available = true, want false for a missing report")
	}
	if !strings.Contains(got.Message, "$otel-audit") {
		t.Errorf("Message = %q, want it to name $otel-audit", got.Message)
	}
	// The absolute path must not leak through this CORS-open endpoint.
	if strings.Contains(got.Message, string(filepath.Separator)+"tmp") || filepath.IsAbs(got.Source) {
		t.Errorf("Message/Source leaked an absolute path: %q / %q", got.Message, got.Source)
	}
}

